"""Quote-only scheduling must preserve qualified and degraded selection order."""
from datetime import date, datetime
from types import SimpleNamespace
from zoneinfo import ZoneInfo

import pytest

from app.core.config import Settings
from app.providers.akshare import AKShareProvider
from app.providers.base import MarketProvider, ProviderError
from app.providers.composite import CompositeProvider
from app.providers.types import BarRecord, InstrumentRecord, QuoteRecord

DAY = date(2026, 10, 16)
AT = datetime(2026, 10, 16, 14, 50, tzinfo=ZoneInfo("Asia/Shanghai"))
A, B = "510300.SH", "512480.SH"


def quote(code, source, price=1.1, *, realtime=True, reason=None):
    return QuoteRecord(ts_code=code, quote_time=AT, price=price, source=source,
                       is_realtime=realtime, degraded_reason=reason)


class Quotes(MarketProvider):
    def __init__(self, name, rows=(), *, capability="unknown", error=None, calls=None):
        self.name, self.rows, self.quote_selection_capability = name, rows, capability
        self.error, self.calls = error, [] if calls is None else calls
    def fetch_spot_quotes(self, codes):
        self.calls.append((self.name, "quotes", list(codes)))
        if self.error:
            raise self.error
        return [row for row in self.rows if row.ts_code in codes]
    def list_instruments(self, codes=None):
        self.calls.append((self.name, "catalog", codes))
        return [InstrumentRecord(ts_code=A, symbol=A[:6], name=self.name)]
    def fetch_daily_bars(self, code, start, end):
        self.calls.append((self.name, "daily", code))
        return [BarRecord(ts_code=code, trade_date=end, open=1, high=1, low=1, close=1,
                          volume=100, amount=100, source="akshare:em:v101", adjust="none")]
    def fetch_news(self, since_hours=24):
        self.calls.append((self.name, "news", since_hours))
        return []


def test_definitely_degraded_adapter_is_not_fetched_before_complete_qualified_scope():
    calls = []
    slow = Quotes("akshare", [quote(A, "akshare:em:v101", realtime=False)],
                  capability="degraded_only", calls=calls)
    fast = Quotes("sina", [quote(A, "sina:hq_sinajs:v1")], calls=calls)
    providers = [slow, fast]
    composite = CompositeProvider(providers)
    assert composite.fetch_spot_quotes([A])[0].source == "sina:hq_sinajs:v1"
    assert calls == [("sina", "quotes", [A])]
    assert composite.providers is providers and providers == [slow, fast]
    skipped = next(item for item in composite.last_trace if item.provider == "akshare")
    assert skipped.status == "skipped" and skipped.latency_ms == 0 and skipped.record_count == 0
    assert "deferred" in skipped.reason and skipped.quality_hash is None


@pytest.mark.parametrize("duplicate_codes", [False, True])
@pytest.mark.parametrize("candidate_kind", ["qualified", "partial", "degraded", "daily", "empty", "failed", "missing"])
def test_deferred_calls_preserve_original_fallback_result(candidate_kind, duplicate_codes):
    original = [quote(A, "akshare:em:v101", 1.01, realtime=False), quote(B, "akshare:em:v101", 1.02, realtime=False)]
    candidates = {
        "qualified": [quote(A, "sina:hq_sinajs:v1", 2.01), quote(B, "sina:hq_sinajs:v1", 2.02)],
        "partial": [quote(A, "sina:hq_sinajs:v1", 2.01)],
        "degraded": [quote(A, "sina:hq_sinajs:v1", 2.01, realtime=False), quote(B, "sina:hq_sinajs:v1", 2.02, realtime=False)],
        "daily": [quote(A, "tushare:fund_daily:v101", 2.01, realtime=False)], "empty": [], "failed": [], "missing": []}
    def build(capability):
        return CompositeProvider([
            Quotes("akshare", original[:1] if candidate_kind == "missing" else original, capability=capability),
            Quotes("candidate", candidates[candidate_kind], error=ProviderError("synthetic") if candidate_kind == "failed" else None),
            Quotes("last", [] if candidate_kind == "missing" else [quote(B, "last", 9.0, realtime=False)])])
    legacy, routed = build("unknown"), build("degraded_only")
    codes = [A, A, B, B] if duplicate_codes else [A, B]
    result = routed.fetch_spot_quotes(codes)
    assert [row.to_dict() for row in result] == [row.to_dict() for row in legacy.fetch_spot_quotes(codes)]
    # Golden selection generated by executing the unmodified composite module
    # from f3ab310de25b7d2fbe66e654842367c741d3b522 on these fixed return values.
    expected = [(A, "akshare:em:v101", 1.01, False, None), (B, "akshare:em:v101", 1.02, False, None)]
    if candidate_kind == "qualified":
        expected = [(A, "sina:hq_sinajs:v1", 2.01, True, None), (B, "sina:hq_sinajs:v1", 2.02, True, None)]
    elif candidate_kind == "partial":
        expected = [(A, "sina:hq_sinajs:v1", 2.01, True, None), expected[1]]
    elif candidate_kind == "missing":
        expected = expected[:1]
    assert [(row.ts_code, row.source, row.price, row.is_realtime, row.degraded_reason) for row in result] == expected
    assert sorted(set(codes)-{row.ts_code for row in result}) == ([B] if candidate_kind == "missing" else [])
    if candidate_kind != "qualified":
        trace = next(item for item in routed.last_trace if item.provider == "akshare")
        assert "deferred" in trace.reason


def test_unknown_adapter_named_akshare_keeps_existing_qualified_priority():
    first = Quotes("akshare", [quote(A, "qualified_custom", 1.01)])
    later = Quotes("sina", [quote(A, "sina:hq_sinajs:v1", 9)])
    assert CompositeProvider([first, later]).fetch_spot_quotes([A])[0].price == 1.01
    assert not later.calls


def test_duck_typed_unknown_adapter_without_capability_keeps_priority():
    first = SimpleNamespace(name="unknown_duck", fetch_spot_quotes=lambda codes: [quote(A, "unknown_duck", 1.01)])
    later = Quotes("sina", [quote(A, "sina:hq_sinajs:v1", 9)])
    assert not hasattr(first, "quote_selection_capability")
    assert CompositeProvider([first, later]).fetch_spot_quotes([A])[0].price == 1.01
    assert not later.calls


def test_degraded_capability_contradiction_is_a_hard_error_even_with_partial_selected():
    liar = Quotes("declared_degraded", [quote(B, "actually_qualified")], capability="degraded_only")
    first = Quotes("candidate", [quote(A, "qualified")])
    with pytest.raises(ProviderError, match="capability"):
        CompositeProvider([liar, first]).fetch_spot_quotes([A, B])


def test_real_akshare_adapter_declaration_matches_nonrealtime_normalization():
    client = SimpleNamespace(fund_etf_spot_em=lambda: [{"代码": A[:6], "最新价": 1.1,
        "更新时间": AT.isoformat(), "成交量": 100, "成交额": 110}])
    adapter = AKShareProvider(Settings(_env_file=None), ak_client=client)
    assert adapter.quote_selection_capability == "degraded_only"
    rows = adapter.fetch_spot_quotes([A])
    assert rows and all(not CompositeProvider._quote_is_qualified(row) for row in rows)


def test_quote_route_does_not_reorder_catalog_daily_or_news():
    calls = []
    first = Quotes("first", capability="degraded_only", calls=calls)
    second = Quotes("second", calls=calls)
    provider = CompositeProvider([first, second])
    assert provider.list_instruments([A])[0].name == "first"
    provider.fetch_daily_bars(A, DAY, DAY)
    provider.fetch_news()
    assert [name for name, operation, _ in calls if operation == "catalog"] == ["first"]
    assert [name for name, operation, _ in calls if operation == "daily"] == ["first"]
    assert [name for name, operation, _ in calls if operation == "news"] == ["first", "second"]


